# =========================================================
# TCM Intent Router V6.9
#
# 核心原则：
#
# 1. 用户自己的症状/身体状态
#       -> consultation
#
# 2. 个人用药、辨证、调理请求
#       -> consultation
#
# 3. 纯知识问题
#       -> knowledge
#
# 个人医疗语境优先于“什么/原因/辨证”等知识型词语。
# =========================================================


def normalize(text):

    text = str(
        text or ""
    )

    text = text.strip()

    text = re.sub(
        r"\s+",
        "",
        text
    )

    return text


# =========================================================
# 通用pattern匹配
# =========================================================

def contains_any_pattern(
    text,
    patterns
):

    text = normalize(
        text
    )

    for pattern in patterns:

        if re.search(
            pattern,
            text
        ):
            return True

    return False


