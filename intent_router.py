def is_explicit_knowledge_lookup(text):

    q = normalize(text)


    # -----------------------------------------------------
    # 个人用药 / 适用性决策必须继续 consultation
    # -----------------------------------------------------

    personal_decision_patterns = (
        "适合我",
        "我适合",
        "我能吃",
        "我能不能吃",
        "我可以吃",
        "我可不可以吃",
        "我要不要吃",
        "我该不该吃",
        "能给我用",
        "能不能给我用",
        "对我有用吗",
        "对我合适吗",
    )


    if any(
        x in q
        for x in personal_decision_patterns
    ):
        return False


    # -----------------------------------------------------
    # 明确个人症状上下文必须继续 consultation
    # -----------------------------------------------------

    personal_symptom_patterns = (
        "我最近",
        "我这几天",
        "我这两天",
        "我一直",
        "我现在",
        "我昨天",
        "我今天",
        "我的症状",
        "我的情况",
        "我出现",
        "我感觉",
        "我觉得",
        "我有点",
        "我总是",
        "我经常",
    )


    if any(
        x in q
        for x in personal_symptom_patterns
    ):
        return False


    # -----------------------------------------------------
    # 明确知识查询
    #
    # “我想了解一下”只是语言表达，
    # 不应仅因为包含“我”就判 consultation。
    # -----------------------------------------------------

    knowledge_openers = (
        "我想了解",
        "我想了解一下",
        "我想知道",
        "想了解一下",
        "想了解",
        "请介绍",
        "请说明",
        "请解释",
    )


    knowledge_targets = (
        "传统中药资料",
        "中药资料",
        "中医药资料",
        "中医基础理论",
        "中医基础概念",
        "传统功效",
        "传统功能",
    )


    knowledge_questions = (
        "功能是什么",
        "功效是什么",
        "作用是什么",
        "有什么功能",
        "有什么功效",
        "有什么作用",
        "是什么意思",
        "是什么概念",
        "什么叫",
        "何谓",
        "怎么理解",
        "如何理解",
    )


    has_opener = any(
        x in q
        for x in knowledge_openers
    )

    has_target = any(
        x in q
        for x in knowledge_targets
    )

    has_question = any(
        x in q
        for x in knowledge_questions
    )


    # 强证据：
    # 知识资料语境 + 明确知识问题
    if (
        has_target
        and has_question
    ):
        return True


    # “我想了解/我想知道” + 知识问题
    # 同样属于知识查询
    if (
        has_opener
        and has_question
    ):
        return True


    return False



def detect_intent(text):

    # =====================================================
    # V6.15.1 Explicit Knowledge Lookup
    #
    # 必须在泛化的个人“我...”判断之前执行。
    # =====================================================

    if is_explicit_knowledge_lookup(text):
        return "knowledge"


    text = normalize(
        text
    )


    if not text:

        return "consultation"


    personal = contains_personal_context(
        text
    )

    symptom = contains_symptom(
        text
    )

    consultation_request = (
        contains_any_pattern(
            text,
            CONSULTATION_REQUEST_PATTERNS
        )
    )


    # =====================================================
    # 1. 个人症状最高优先
    #
    # 例如：
    #
    # 我腰酸，还总觉得累，属于什么情况？
    #
    # 即使出现“什么情况”，也不能进入knowledge。
    # =====================================================

    if (
        personal
        and symptom
    ):

        return "consultation"


    # =====================================================
    # 2. 明确要求个人辨证 / 分析 / 用药
    # =====================================================

    if consultation_request:

        # “中医辨证是什么”这类纯知识问题
        # 不应该因为出现“辨证”被误判
        if (
            not personal
            and not symptom
            and re.search(
                r"(什么是|是什么意思|定义)",
                text
            )
        ):

            return "knowledge"

        return "consultation"


    # =====================================================
    # 3. 即使没有“我”，明显描述症状组合，
    #    默认按consultation处理。
    #
    # Safety Router应该在这里之前运行。
    # =====================================================

    if symptom:

        return "consultation"


    # =====================================================
    # 4. 纯知识问法
    # =====================================================

    if contains_any_pattern(
        text,
        KNOWLEDGE_PATTERNS
    ):

        return "knowledge"


    # =====================================================
    # 5. 常见实体直接问法
    #
    # 保守策略：
    # 没有个人症状时才允许知识路由。
    # =====================================================

    if any(
        suffix in text
        for suffix in KNOWLEDGE_ENTITY_SUFFIXES
    ):

        return "knowledge"


    # =====================================================
    # 6. 默认
    #
    # 医疗场景下不确定时，
    # consultation比knowledge更安全：
    # 后续可以继续追问，而不是直接返回知识结论。
    # =====================================================

    return "consultation"


