# =========================================================
# Basic normalization
# =========================================================

def normalize(text):

    text = str(
        text or ""
    ).strip()

    text = re.sub(
        r"\s+",
        "",
        text
    )


    # -----------------------------------------------------
    # 非意愿体重下降
    #
    # 避免：
    # “没有刻意减肥体重却下降”
    #
    # 被“没有”误识别成否定。
    # -----------------------------------------------------

    text = re.sub(
        r"没有(?:刻意)?(?:减肥|控制饮食)"
        r".{0,10}"
        r"体重.{0,5}(?:下降|减轻)",
        "非意愿体重下降",
        text
    )

    text = re.sub(
        r"没(?:有)?(?:刻意)?减肥"
        r".{0,10}"
        r"体重.{0,5}(?:下降|减轻)",
        "非意愿体重下降",
        text
    )

    text = re.sub(
        r"并未(?:刻意)?减肥"
        r".{0,10}"
        r"体重.{0,5}(?:下降|减轻)",
        "非意愿体重下降",
        text
    )


    return text


# =========================================================
# Compatibility API
# =========================================================

def match_all(text, groups):

    text = normalize(
        text
    )

    return all(
        any(
            re.search(
                pattern,
                text
            )
            for pattern
            in group
        )
        for group
        in groups
    )


# =========================================================
# Concept matching
# =========================================================

def concept_state(
    text,
    positive_patterns,
    negative_patterns=None,
):

    """
    返回：
        present
        absent
        unknown

    原理：
    1. 先找所有明确否定span
    2. 位于否定span内部的positive不计入
    3. 以最后一次明确表述为最终状态
    """

    text = normalize(
        text
    )

    negative_patterns = (
        negative_patterns
        or []
    )


    negative_spans = []
    events = []


    # -----------------------------------------------------
    # Negative
    # -----------------------------------------------------

    for pattern in negative_patterns:

        for m in re.finditer(
            pattern,
            text
        ):

            negative_spans.append(
                (
                    m.start(),
                    m.end()
                )
            )

            events.append(
                (
                    m.start(),
                    "absent"
                )
            )


    # -----------------------------------------------------
    # Positive
    # -----------------------------------------------------

    for pattern in positive_patterns:

        for m in re.finditer(
            pattern,
            text
        ):

            start = m.start()
            end = m.end()


            inside_negative = any(
                start >= ns
                and end <= ne
                for ns, ne
                in negative_spans
            )


            if inside_negative:
                continue


            events.append(
                (
                    start,
                    "present"
                )
            )


    if not events:
        return "unknown"


    events.sort(
        key=lambda x: x[0]
    )


    return events[-1][1]


