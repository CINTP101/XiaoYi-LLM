def present(
    facts,
    key
):

    return (
        facts.get(key)
        == "present"
    )


# =========================================================
# Hard Safety Route
# =========================================================

def route(text):

    facts = analyze(
        text
    )


    # =====================================================
    # URGENT
    # =====================================================

    # -----------------------------------------------------
    # 1. Chest pain + dyspnea
    # -----------------------------------------------------

    if (
        present(
            facts,
            "chest_pain"
        )
        and
        present(
            facts,
            "dyspnea"
        )
    ):

        return "urgent"


    # -----------------------------------------------------
    # 2. Severe respiratory distress alone
    # -----------------------------------------------------

    if present(
        facts,
        "severe_dyspnea"
    ):

        return "urgent"


    # -----------------------------------------------------
    # 3. Possible acute focal neurological event
    # -----------------------------------------------------

    if (
        present(
            facts,
            "speech_deficit"
        )
        and
        present(
            facts,
            "unilateral_deficit"
        )
    ):

        return "urgent"


    # -----------------------------------------------------
    # 4. Hematemesis
    # -----------------------------------------------------

    if present(
        facts,
        "hematemesis"
    ):

        return "urgent"


    # -----------------------------------------------------
    # 5. Large-volume hematochezia
    # -----------------------------------------------------

    if present(
        facts,
        "large_hematochezia"
    ):

        return "urgent"


    # =====================================================
    # REFER
    # =====================================================

    # -----------------------------------------------------
    # 1. Fatigue + dizziness + pallor
    # -----------------------------------------------------

    if (
        present(
            facts,
            "fatigue"
        )
        and
        present(
            facts,
            "dizziness"
        )
        and
        present(
            facts,
            "pallor"
        )
    ):

        return "refer"


    # -----------------------------------------------------
    # 2. Fatigue + unexplained weight loss
    # -----------------------------------------------------

    if (
        present(
            facts,
            "fatigue"
        )
        and
        present(
            facts,
            "weight_loss"
        )
    ):

        return "refer"


    # -----------------------------------------------------
    # 3. Palpitations + dizziness
    # -----------------------------------------------------

    if (
        present(
            facts,
            "palpitation"
        )
        and
        present(
            facts,
            "dizziness"
        )
    ):

        return "refer"


    return None


